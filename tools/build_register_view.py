def render_markdown(doc: dict) -> str:
    entries = sorted(doc["entries"], key=lambda e: num(e["id"]))
    by_actor = Counter(e["first_articulation"]["actor_context"] for e in entries)
    by_control = Counter(e["prospective_control"]["state"] for e in entries)
    review = Counter(e["human_review"]["status"] for e in entries)
    rows = sum(len(e["affected_objects"]) for e in entries)

    out = [
        "# Deficiency register — classification\n\n",
        "**Generated** by `tools/build_register_view.py` from "
        "`corpus/artifacts/deficiency-register.json`. Do not edit this file; edit the artifact.\n\n",
        "[`corpus/deficiencies.md`](deficiencies.md) is **canonical**. This is metadata over it, "
        "and it carries no detail about what any defect actually was — follow the links.\n\n",
        "---\n\n## What this classification does and does not establish\n\n",
        "It records, per entry, where the defect was **first substantively articulated in preserved "
        "material**, what it affects, whether each affected object is repairable, and whether a "
        "forward control exists and has been validated.\n\n",
        "It does **not** establish that any of those judgements is correct. They were made by the "
        "annotator, which is a party to the record. `tools/check_register.py` verifies structure, "
        "one-to-one coverage, vocabulary, and that each entry's prose has not changed since it was "
        "classified. **It never verifies meaning**, and a deterministic rule that claimed to would "
        "be D-25 over again.\n\n",
        f"**{review.get('reviewed_by_custodian', 0)} of {len(entries)}** classifications have been "
        "read by a human against the prose.\n\n",
        "On attribution: this project cannot observe who first *privately noticed* a defect, so it "
        "records where one was first *written down*, with an evidence class. A question that "
        "prompted an investigation is recorded as a **trigger**, not as the finding.\n\n",
        "---\n\n## Counts\n\n### First substantive articulation\n\n| Where | Entries |\n|---|---|\n",
    ]
    for actor, count in sorted(by_actor.items(), key=lambda kv: -kv[1]):
        out.append(f"| {ACTOR_LABEL[actor]} | {count} |\n")

    reviewer_found = sorted(
        (e["id"] for e in entries
         if e["first_articulation"]["actor_context"] == "actor_designated_review_round_invocation"),
        key=num)
    if reviewer_found:
        out.append(
            f"\n**{len(reviewer_found)} entries — {reviewer_found[0]} through {reviewer_found[-1]} — "
            "were first substantively articulated in preserved designated review-round submissions.** "
            "That is narrower than \"found by the reviewers\", and unlike it, checkable.\n")

    out.append("\n### Prospective control\n\n| State | Entries |\n|---|---|\n")
    for state in CONTROL_LABEL:
        if by_control.get(state):
            out.append(f"| {CONTROL_LABEL[state]} | {by_control[state]} |\n")

    out.extend([
        f"\n### Affected objects\n\n**{rows} affected-object rows across {len(entries)} entries.** "
        "Repairability is recorded per object because it is not a property of a deficiency: D-09's "
        "raw transcript is not repairable while its `segments.json` annotation was corrected, and a "
        "single yes/no is false for one of them whichever way it is written.\n\n",
        "---\n\n## Entries\n\n",
    ])

    for e in entries:
        fa = e["first_articulation"]
        out.append(f"### {e['id']} — {e['title']}\n\n")
        out.append(f"[Full entry](deficiencies.md#{anchor(e)})\n\n")
        out.append(f"- **First articulated:** {ACTOR_LABEL[fa['actor_context']]}")
        if fa.get("actor_label"):
            out.append(f" — {fa['actor_label']}")
        out.append(f", {fa['date_utc']} · evidence: *{EVIDENCE_LABEL[fa['evidence_class']]}*\n")
        out.append(f"  - where: `{fa['where']}`\n")
        if "investigation_triggered_by" in e:
            t = e["investigation_triggered_by"]
            label = t.get("actor_label") or ACTOR_LABEL[t["actor_context"]]
            out.append(f"- **Triggered by** {label}: {t['what']}\n")
        for n in e.get("narrowed_or_corrected_by", []):
            out.append(f"- **Narrowed/corrected** by {n['actor_label']} ({n['round']}): {n['what']}\n")
        out.append(f"- **Prospective control:** {CONTROL_LABEL[e['prospective_control']['state']]}")
        if e["prospective_control"].get("mechanism"):
            out.append(f" — {e['prospective_control']['mechanism']}")
        out.append("\n")
        if "remediation_effort" in e:
            r = e["remediation_effort"]
            out.append(f"- **Effort:** {r['estimate'].replace('remediation_effort_', '')} — {r['basis']}\n")
        for claim in e.get("invalidates", []):
            out.append(f"- **Invalidates:** {claim}\n")
        out.append(f"- **Human review:** {e['human_review']['status']}\n")
        out.append("\n| Affected object | Repairable? | Remediation |\n|---|---|---|\n")
        for o in e["affected_objects"]:
            note = f" <br><sub>{o['note']}</sub>" if o.get("note") else ""
            out.append(f"| {o['object']}{note} | {REPAIR_LABEL[o['repairability']]} "
                       f"| {REMEDIATION_LABEL[o['remediation_state']]} |\n")
        out.append("\n")

    return "".join(out)


def anchor(entry: dict) -> str:
    """GitHub's heading anchor for this entry's markdown heading."""
    text = f"{entry['id']} — {entry['title']}".lower()
    keep = [c if (c.isalnum() or c in " -") else "" for c in text]
    return "".join(keep).strip().replace(" ", "-")


