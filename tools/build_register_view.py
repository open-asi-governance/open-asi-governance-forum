"""Generate the deficiency register views from the structured artifact.

    python3 tools/build_register_view.py

Writes three files, all derived, none hand-edited:

    corpus/deficiency-register.md   metadata table for GitHub readers
    docs/deficiencies.html          the self-contained public view
    docs/deficiencies.md            plain-text mirror of the register itself

`corpus/deficiencies.md` remains **canonical**. These are annotation over it and
never replace it: the view carries classification and counts, and sends the
reader to the prose for what actually happened.

The plain-text mirror exists because this corpus has evidence that agents cannot
read the alternatives. Gemini's round-01 environment could reach neither
`raw.githubusercontent.com` nor the `/blob/` UI, which renders via JavaScript and
returns a navigation shell to automated readers. GitHub Pages serves any file at
a predictable path from the same origin as the page, so the mirror is reachable
where those two are not.

Every number on these pages is computed from the artifact. None is typed. The
count this repository published for months was typed, and it was wrong in three
different places at once.

Deterministic: no clock, no randomness, sorted throughout.
"""

